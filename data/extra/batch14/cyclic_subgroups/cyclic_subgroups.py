def generated(g, n):
    out = [0]
    x = g % n
    while x != 0:
        out.append(x)
        x = (x + g) % n
    return sorted(out)
def fmt(xs):
    return "[" + ", ".join(str(x) for x in xs) + "]"
n = 12
for d in range(1, n + 1):
    if n % d == 0:
        sub = generated(n // d, n)
        gens = [g for g in range(n) if generated(g, n) == sub]
        print(f"order {d:>2}: {fmt(sub)} generated by {fmt(gens)}")
h = generated(4, n)
print(f"cosets of {fmt(h)}:")
covered = set()
for a in range(n):
    if a not in covered:
        coset = sorted((x + a) % n for x in h)
        covered.update(coset)
        print(f"  {a} + H = {fmt(coset)}")
print(f"12 elements / 3 per coset = {n // len(h)} cosets")
