def digit_sum(n):
    s = 0
    while n > 0:
        s += n % 10
        n //= 10
    return s

limit = 10000
makers = {}
for m in range(1, limit + 1):
    v = m + digit_sum(m)
    if v <= limit:
        makers.setdefault(v, []).append(m)
selfs = [n for n in range(1, limit + 1) if n not in makers]
print(f"self numbers below 100: {[x for x in selfs if x < 100]}")
print(f"{len(selfs)} self numbers up to {limit}")
for n in [21, 101, 1000, 1016]:
    gens = makers.get(n, [])
    if not gens:
        print(f"{n}: self number, no generator")
    else:
        print(f"{n}: generated by {gens}")
multi = [n for n in range(1, 201) if len(makers.get(n, [])) > 1]
print(f"numbers up to 200 with two generators: {multi}")
